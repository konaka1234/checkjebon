const locales = { nl: 'nl-NL', en: 'en-GB' };
const priceFormats = Object.fromEntries(Object.entries(locales).map(([language, locale]) => [
	language,
	new Intl.NumberFormat(locale, { minimumFractionDigits: 2, maximumFractionDigits: 2, useGrouping: false })
]));

function initialLanguage()
{
	const requested = new URLSearchParams(window.location.search).get('lang');
	if (requested === 'en' || requested === 'nl')
	{
		return requested;
	}
	return localStorage.getItem('checkjebonLanguage') === 'en' ? 'en' : 'nl';
}

Vue.mixin({
	methods: {
		t(key, values = {}) {
			return messages[this.$root.language][key].replace(/\{(\w+)\}/g, (match, name) => values[name]);
		},
		formatPrice(value) {
			return value > 0 ? priceFormats[this.$root.language].format(value) : '-';
		},
		formatCount(value) {
			return value.toLocaleString(locales[this.$root.language]);
		},
		formatDate(value) {
			const date = new Date(value);
			return Number.isNaN(date.getTime()) ? value : date.toLocaleDateString(locales[this.$root.language]);
		},
		formatAmount(value) {
			if (!value) return value;
			let amount = value.toLowerCase();
			const match = amount.match(/^(\d+) (gram|milliliter)$/);
			if (match && Number(match[1]) >= 1000)
			{
				const unit = match[2] === 'gram' ? 'kilogram' : 'liter';
				amount = (Number(match[1]) / 1000) + ' ' + unit;
			}
			if (this.$root.language === 'en')
			{
				return amount.replace(/(\d),(?=\d)/g, '$1.')
					.replace(/\b(?:kilogram|kilo)\b/g, 'kg')
					.replace(/\b(?:gram|gr)\b/g, 'g')
					.replace(/\bmilliliter\b/g, 'ml')
					.replace(/\bliter\b/g, 'l')
					.replace(/\bper stuk\b/g, 'each')
					.replace(/\b(?:stuks?|st)\b/g, 'pcs');
			}
			return amount;
		}
	}
});
